/**
 * Robust RFC-4180 CSV / TSV Parser
 * Correctly handles quotes, escaped quotes (""), newlines inside quotes, and custom delimiters.
 */
export function parseDelimitedRows(text, delimiter = null) {
  if (!text) return [];

  // Strip UTF-8 BOM if present
  let cleanText = text.replace(/^\uFEFF/, '').trim();

  // Strip Anki comment lines at start (e.g. #separator:tab, #html:true, #tags column:3)
  const lines = cleanText.split(/\r?\n/);
  const contentLines = [];
  let ankiDetectedSep = null;

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('#separator:')) {
      const sepName = trimmed.replace('#separator:', '').trim().toLowerCase();
      if (sepName === 'tab' || sepName === '\\t') ankiDetectedSep = '\t';
      else if (sepName === 'comma' || sepName === ',') ankiDetectedSep = ',';
      else if (sepName === 'semicolon' || sepName === ';') ankiDetectedSep = ';';
    } else if (trimmed.startsWith('#')) {
      // skip other comment headers
      continue;
    } else {
      contentLines.push(line);
    }
  }

  cleanText = contentLines.join('\n');
  if (!cleanText.trim()) return [];

  // Auto-detect delimiter if not forced
  if (!delimiter) {
    if (ankiDetectedSep) {
      delimiter = ankiDetectedSep;
    } else {
      // Count delimiters in first few lines
      const sample = cleanText.split('\n').slice(0, 5).join('\n');
      const tabCount = (sample.match(/\t/g) || []).length;
      const commaCount = (sample.match(/,/g) || []).length;
      const semiCount = (sample.match(/;/g) || []).length;
      const pipeCount = (sample.match(/\|/g) || []).length;

      if (tabCount >= 2 && tabCount >= commaCount) delimiter = '\t';
      else if (commaCount >= 2) delimiter = ',';
      else if (semiCount >= 2) delimiter = ';';
      else if (pipeCount >= 2) delimiter = '|';
      else delimiter = '\t'; // default to tab
    }
  }

  // Tokenize rows and fields
  const rows = [];
  let currentRow = [];
  let currentField = '';
  let inQuotes = false;
  let i = 0;
  const len = cleanText.length;

  while (i < len) {
    const char = cleanText[i];
    const nextChar = i + 1 < len ? cleanText[i + 1] : '';

    if (inQuotes) {
      if (char === '"' && nextChar === '"') {
        currentField += '"';
        i += 2;
        continue;
      } else if (char === '"') {
        inQuotes = false;
        i++;
        continue;
      } else {
        currentField += char;
        i++;
        continue;
      }
    } else {
      if (char === '"') {
        inQuotes = true;
        i++;
        continue;
      } else if (char === delimiter) {
        currentRow.push(currentField);
        currentField = '';
        i++;
        continue;
      } else if (char === '\r' && nextChar === '\n') {
        currentRow.push(currentField);
        rows.push(currentRow);
        currentRow = [];
        currentField = '';
        i += 2;
        continue;
      } else if (char === '\n' || char === '\r') {
        currentRow.push(currentField);
        rows.push(currentRow);
        currentRow = [];
        currentField = '';
        i++;
        continue;
      } else {
        currentField += char;
        i++;
        continue;
      }
    }
  }

  if (currentField.length > 0 || currentRow.length > 0) {
    currentRow.push(currentField);
    rows.push(currentRow);
  }

  return rows;
}

/**
 * Clean & normalize HTML from Anki or web exports
 */
function cleanHtml(html) {
  if (!html) return '';
  let text = html
    .replace(/<br\s*[\/]?>/gi, '\n')
    .replace(/<\/div>/gi, '\n')
    .replace(/<div>/gi, '')
    .replace(/<\/p>/gi, '\n\n')
    .replace(/<p>/gi, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");

  // Keep clean inline tags like <b>, <i>, <code>, <u>, <em>, <strong>
  // Strip dangerous or layout tags
  text = text.replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '');
  text = text.replace(/<style\b[^<]*(?:(?!<\/style>)<[^<]*)*<\/style>/gi, '');
  return text.trim();
}

/**
 * Detect Cloze deletion syntax (e.g. {{c1::answer}} or {{answer}})
 */
function detectCloze(text) {
  if (!text) return null;
  // Anki-style {{c1::answer}} or {{c1::answer::hint}}
  if (/\{\{c\d+::.*?\}\}/i.test(text)) {
    return text;
  }
  // RemNote or simple cloze {{answer}}
  if (/\{\{[^{}]+?\}\}/.test(text)) {
    let clozeIdx = 1;
    // Normalize simple {{answer}} to {{c1::answer}}
    return text.replace(/\{\{([^{}]+?)\}\}/g, (_, match) => {
      if (match.startsWith('c') && match.includes('::')) return `{{${match}}}`;
      const res = `{{c${clozeIdx}::${match}}}`;
      clozeIdx++;
      return res;
    });
  }
  return null;
}

/**
 * Auto-detect the likely service based on filename and text content
 */
export function autoDetectService(text, filename = '') {
  const ext = filename ? filename.toLowerCase().split('.').pop() : '';
  const trimmed = text.trim();

  // 1. JSON
  if (ext === 'json' || (trimmed.startsWith('{') && trimmed.endsWith('}'))) {
    try {
      const parsed = JSON.parse(trimmed);
      if (parsed.cards && parsed.groups) return 'studycards';
      if (Array.isArray(parsed) || parsed.cards || parsed.terms) return 'knowt';
    } catch (e) {
      // not valid JSON
    }
  }

  // 2. Anki Comments
  if (trimmed.startsWith('#separator:') || trimmed.startsWith('#html:') || trimmed.startsWith('#tags column:')) {
    return 'anki';
  }

  // 3. RemNote (Markdown with :: or ::: or ;;)
  if (ext === 'md' || /(?:^|\n).+?\s*:::\s*.+/m.test(trimmed) || /(?:^|\n).+?\s*::\s*.+/m.test(trimmed) || /(?:^|\n).+?\s*;;/m.test(trimmed)) {
    return 'remnote';
  }

  // 4. Brainscape CSV header
  if (ext === 'csv' || /^["']?Question["']?\s*,\s*["']?Answer["']?/i.test(trimmed)) {
    return 'brainscape';
  }

  // 5. Quizlet or Universal TSV
  if (ext === 'tsv' || (trimmed.split('\n').length > 1 && trimmed.includes('\t'))) {
    return 'quizlet';
  }

  if (ext === 'csv') {
    return 'delimited';
  }

  return 'quizlet';
}

/**
 * Main parse dispatcher
 */
export function parseImport(rawText, serviceId = 'auto', options = {}) {
  const filename = typeof options === 'string' ? options : (options?.fileName || '');
  let activeService = serviceId;
  if (!activeService || activeService === 'auto') {
    activeService = autoDetectService(rawText, filename);
  }

  let result = null;

  switch (activeService) {
    case 'studycards':
      result = parseStudyCardsJson(rawText);
      break;
    case 'quizlet':
      result = parseQuizlet(rawText, options);
      break;
    case 'anki':
      result = parseAnki(rawText);
      break;
    case 'remnote':
      result = parseRemNote(rawText);
      break;
    case 'brainscape':
      result = parseBrainscape(rawText);
      break;
    case 'cram':
      result = parseCram(rawText);
      break;
    case 'knowt':
      result = parseKnowt(rawText, options);
      break;
    case 'delimited':
    default:
      result = parseDelimited(rawText, options);
      break;
  }

  // Suggest deck name from filename or options if available
  if (options && options.deckName && (!result.deckName || result.deckName.includes('Deck'))) {
    result.deckName = options.deckName;
  } else if (filename) {
    const baseName = filename.split(/[\\/]/).pop() || filename;
    const cleanName = baseName.replace(/\.[^/.]+$/, '').replace(/[_-]/g, ' ').trim();
    if (cleanName && (!result.deckName || result.deckName === 'Imported Deck')) {
      result.deckName = cleanName.charAt(0).toUpperCase() + cleanName.slice(1);
    }
  }

  return result;
}

export const parseImportData = (rawText, serviceId = 'auto', filename = '') =>
  parseImport(rawText, serviceId, { fileName: filename });

/**
 * Detect Quizlet separators (card separator and term/definition separator)
 * Auto-detects whether cards are separated by semicolon (;) or newline (\n),
 * and whether fields are separated by comma (,) or tab (\t).
 */
export function detectQuizletSeparators(text, preferredCardSep = null, preferredFieldSep = null) {
  let cardSep = preferredCardSep && preferredCardSep !== 'auto' ? preferredCardSep : null;
  let fieldSep = preferredFieldSep && preferredFieldSep !== 'auto' ? preferredFieldSep : null;

  const clean = text.replace(/^\uFEFF/, '').trim();
  const semiCount = (clean.match(/;/g) || []).length;
  const tabCount = (clean.match(/\t/g) || []).length;
  const commaCount = (clean.match(/,/g) || []).length;

  if (!cardSep) {
    if (semiCount >= 2) {
      const semiChunks = clean.split(';').map(c => c.trim()).filter(Boolean);
      const semiCommaHits = semiChunks.filter(c => c.includes(',')).length;
      const semiTabHits = semiChunks.filter(c => c.includes('\t')).length;
      const semiValidHits = Math.max(semiCommaHits, semiTabHits);
      const semiRatio = semiChunks.length > 0 ? semiValidHits / semiChunks.length : 0;

      const lines = clean.split(/\r?\n/).map(c => c.trim()).filter(Boolean);
      const lineCommaHits = lines.filter(c => c.includes(',')).length;
      const lineTabHits = lines.filter(c => c.includes('\t')).length;
      const lineValidHits = Math.max(lineCommaHits, lineTabHits);
      const lineRatio = lines.length > 0 ? lineValidHits / lines.length : 0;

      // If semicolon splitting gives a higher proportion of valid cards or ends with ';'
      if (semiRatio >= 0.6 && (semiRatio > lineRatio || clean.endsWith(';'))) {
        cardSep = ';';
      } else {
        cardSep = '\n';
      }
    } else {
      cardSep = '\n';
    }
  }

  if (!fieldSep) {
    if (cardSep === ';') {
      const chunks = clean.split(';').map(c => c.trim()).filter(Boolean);
      const tabHits = chunks.filter(c => c.includes('\t')).length;
      const commaHits = chunks.filter(c => c.includes(',')).length;
      if (tabHits >= commaHits && tabHits > 0) fieldSep = '\t';
      else if (commaHits > 0) fieldSep = ',';
      else fieldSep = ',';
    } else {
      const sample = clean.split(/\r?\n/).slice(0, 10).join('\n');
      const sampleTabs = (sample.match(/\t/g) || []).length;
      const sampleCommas = (sample.match(/,/g) || []).length;
      if (sampleTabs >= 2 && sampleTabs >= sampleCommas) fieldSep = '\t';
      else if (sampleCommas >= 2) fieldSep = ',';
      else fieldSep = '\t';
    }
  }

  return { cardSeparator: cardSep, fieldSeparator: fieldSep };
}

/**
 * 1. Parse Quizlet Export
 * Supports both standard newline-separated exports and semicolon-separated exports
 * (commonly used when cards contain multi-line text, lists, and bullet points).
 */
export function parseQuizlet(text, options = {}) {
  const cleanText = text.replace(/^\uFEFF/, '').trim();
  if (!cleanText) {
    return buildResult('Quizlet', [], [], 0);
  }

  const { cardSeparator, fieldSeparator } = detectQuizletSeparators(
    cleanText,
    options?.cardSeparator,
    options?.fieldSeparator
  );

  if (cardSeparator === ';') {
    // Semicolon-separated cards (Quizlet export with "Between cards: Semicolon")
    // Correctly preserves newlines, bullet lists, and multi-line answers within cards
    const rawChunks = cleanText.split(';');
    const cards = [];
    const warnings = [];
    let lineNum = 0;

    for (let i = 0; i < rawChunks.length; i++) {
      const chunk = rawChunks[i].trim();
      if (!chunk) continue;
      lineNum++;

      if (chunk.includes(fieldSeparator)) {
        let sepIdx = -1;

        // Smart delimiter boundary: if question ends with ? followed by fieldSeparator
        // e.g. "What are humans: class, order, superfamily and tribe?,class-mammalia..."
        if (chunk.includes('?' + fieldSeparator)) {
          sepIdx = chunk.indexOf('?' + fieldSeparator) + 1;
        } else if (chunk.includes('?\n' + fieldSeparator)) {
          sepIdx = chunk.indexOf('?\n' + fieldSeparator) + 2;
        } else {
          sepIdx = chunk.indexOf(fieldSeparator);
        }

        const front = chunk.substring(0, sepIdx).trim();
        const back = chunk.substring(sepIdx + fieldSeparator.length).trim();

        if (!front && !back) continue;

        if (!front) {
          warnings.push({
            line: lineNum,
            reason: 'Missing term/question (front is empty)',
            rawSnippet: back.substring(0, 40)
          });
          continue;
        }
        if (!back) {
          warnings.push({
            line: lineNum,
            reason: 'Missing definition/answer (back is empty)',
            rawSnippet: front.substring(0, 40)
          });
          continue;
        }

        cards.push({
          front: cleanHtml(front),
          back: cleanHtml(back),
          hint: '',
          tags: ['quizlet'],
          type: CARD_TYPES.BASIC,
          clozeText: '',
          sourceLine: lineNum
        });
      } else {
        // Chunk does not contain fieldSeparator:
        // Occurs when an unescaped semicolon was inside a card's definition text
        if (cards.length > 0) {
          cards[cards.length - 1].back += '; ' + cleanHtml(chunk);
        } else {
          warnings.push({
            line: lineNum,
            reason: 'Orphaned text fragment without term separator',
            rawSnippet: chunk.substring(0, 40)
          });
        }
      }
    }

    const totalValidChunks = rawChunks.filter(c => c.trim()).length;
    const result = buildResult('Quizlet', cards, warnings, totalValidChunks);
    result.detectedSeparators = { cardSeparator, fieldSeparator };
    return result;
  }

  // Standard newline-separated cards
  const rows = parseDelimitedRows(cleanText, fieldSeparator);
  const cards = [];
  const warnings = [];
  let lineNum = 0;

  for (const row of rows) {
    lineNum++;
    if (!row || row.length === 0 || (row.length === 1 && !row[0].trim())) {
      continue; // empty line
    }

    const front = (row[0] || '').trim();
    const back = (row.slice(1).join(fieldSeparator === '\t' ? '\t' : ', ') || '').trim();

    if (!front && !back) continue;

    if (!front) {
      warnings.push({ line: lineNum, reason: 'Missing term/question (front is empty)', rawSnippet: back.substring(0, 40) });
      continue;
    }
    if (!back) {
      warnings.push({ line: lineNum, reason: 'Missing definition/answer (back is empty)', rawSnippet: front.substring(0, 40) });
      continue;
    }

    cards.push({
      front: cleanHtml(front),
      back: cleanHtml(back),
      hint: '',
      tags: ['quizlet'],
      type: CARD_TYPES.BASIC,
      clozeText: '',
      sourceLine: lineNum
    });
  }

  const result = buildResult('Quizlet', cards, warnings, rows.length);
  result.detectedSeparators = { cardSeparator, fieldSeparator };
  return result;
}

/**
 * 2. Parse Anki Plain Text / Notes
 */
export function parseAnki(text) {
  const rows = parseDelimitedRows(text, '\t');
  const cards = [];
  const warnings = [];
  let lineNum = 0;

  for (const row of rows) {
    lineNum++;
    if (!row || row.length === 0 || (row.length === 1 && !row[0].trim())) {
      continue;
    }

    const field1 = (row[0] || '').trim();
    const field2 = row.length > 1 ? (row[1] || '').trim() : '';
    const field3 = row.length > 2 ? (row[2] || '').trim() : '';

    if (!field1 && !field2) continue;

    // Check for Anki Cloze in field 1
    const clozeField1 = detectCloze(field1);
    if (clozeField1) {
      cards.push({
        front: cleanHtml(field1.replace(/\{\{c\d+::(.*?)(?:::.*?)?\}\}/gi, '[...]')),
        back: cleanHtml(field2 || field1),
        hint: '',
        tags: field3 ? field3.split(/\s+/).filter(Boolean) : ['anki'],
        type: CARD_TYPES.CLOZE,
        clozeText: clozeField1,
        sourceLine: lineNum
      });
      continue;
    }

    // Standard Basic Anki card
    if (!field1) {
      warnings.push({ line: lineNum, reason: 'Missing question (Front is empty)', rawSnippet: field2.substring(0, 40) });
      continue;
    }
    if (!field2) {
      warnings.push({ line: lineNum, reason: 'Missing answer (Back is empty)', rawSnippet: field1.substring(0, 40) });
      continue;
    }

    cards.push({
      front: cleanHtml(field1),
      back: cleanHtml(field2),
      hint: '',
      tags: field3 ? field3.split(/\s+/).filter(Boolean) : ['anki'],
      type: CARD_TYPES.BASIC,
      clozeText: '',
      sourceLine: lineNum
    });
  }

  return buildResult('Anki', cards, warnings, rows.length);
}

/**
 * 3. Parse RemNote Markdown / Text
 */
export function parseRemNote(text) {
  const lines = text.split(/\r?\n/);
  const cards = [];
  const warnings = [];
  let lineNum = 0;

  let multilineQuestion = null;
  let multilineBuffer = [];
  let multilineStart = 0;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    lineNum = i + 1;
    const line = rawLine.trim();

    if (!line) continue;

    // Handle multiline continuation (after ';;')
    if (multilineQuestion !== null) {
      if (line.includes('::') || line.endsWith(';;')) {
        // End multiline and process previous
        if (multilineBuffer.length > 0) {
          cards.push({
            front: cleanHtml(multilineQuestion),
            back: cleanHtml(multilineBuffer.join('\n')),
            hint: '',
            tags: ['remnote'],
            type: CARD_TYPES.BASIC,
            clozeText: '',
            sourceLine: multilineStart
          });
        }
        multilineQuestion = null;
        multilineBuffer = [];
      } else {
        multilineBuffer.push(line);
        continue;
      }
    }

    // Multiline trigger (ends with ';;')
    if (line.endsWith(';;') && !line.includes('::')) {
      multilineQuestion = line.replace(/;;$/, '').trim();
      multilineStart = lineNum;
      multilineBuffer = [];
      continue;
    }

    // Bidirectional / Reversible card: Concept ::: Definition
    if (line.includes(':::')) {
      const parts = line.split(':::');
      const front = parts[0].replace(/^[-*•]\s*/, '').trim();
      const back = parts.slice(1).join(':::').trim();
      if (front && back) {
        cards.push({
          front: cleanHtml(front),
          back: cleanHtml(back),
          hint: '',
          tags: ['remnote'],
          type: CARD_TYPES.REVERSIBLE,
          clozeText: '',
          sourceLine: lineNum
        });
      } else {
        warnings.push({ line: lineNum, reason: 'Incomplete reversible card (missing front or back)', rawSnippet: line.substring(0, 40) });
      }
      continue;
    }

    // Standard card: Concept :: Definition
    if (line.includes('::')) {
      const parts = line.split('::');
      const front = parts[0].replace(/^[-*•]\s*/, '').trim();
      const back = parts.slice(1).join('::').trim();
      if (front && back) {
        cards.push({
          front: cleanHtml(front),
          back: cleanHtml(back),
          hint: '',
          tags: ['remnote'],
          type: CARD_TYPES.BASIC,
          clozeText: '',
          sourceLine: lineNum
        });
      } else {
        warnings.push({ line: lineNum, reason: 'Incomplete card (missing front or back)', rawSnippet: line.substring(0, 40) });
      }
      continue;
    }

    // RemNote Cloze: text with {{concept}}
    const cloze = detectCloze(line);
    if (cloze) {
      cards.push({
        front: cleanHtml(line.replace(/\{\{([^{}]+?)\}\}/g, '[...]').replace(/^[-*•]\s*/, '')),
        back: cleanHtml(line.replace(/^[-*•]\s*/, '')),
        hint: '',
        tags: ['remnote'],
        type: CARD_TYPES.CLOZE,
        clozeText: cloze.replace(/^[-*•]\s*/, ''),
        sourceLine: lineNum
      });
      continue;
    }
  }

  // Flush trailing multiline
  if (multilineQuestion && multilineBuffer.length > 0) {
    cards.push({
      front: cleanHtml(multilineQuestion),
      back: cleanHtml(multilineBuffer.join('\n')),
      hint: '',
      tags: ['remnote'],
      type: CARD_TYPES.BASIC,
      clozeText: '',
      sourceLine: multilineStart
    });
  }

  return buildResult('RemNote', cards, warnings, lines.length);
}

/**
 * 4. Parse Brainscape CSV
 */
export function parseBrainscape(text) {
  const rows = parseDelimitedRows(text, ',');
  const cards = [];
  const warnings = [];
  let lineNum = 0;

  let hasHeader = false;
  if (rows.length > 0) {
    const r0 = rows[0].map(c => c.toLowerCase().trim());
    if (r0.includes('question') && r0.includes('answer')) {
      hasHeader = true;
    }
  }

  const startIdx = hasHeader ? 1 : 0;

  for (let i = startIdx; i < rows.length; i++) {
    lineNum = i + 1;
    const row = rows[i];
    if (!row || row.length === 0 || (row.length === 1 && !row[0].trim())) continue;

    const front = (row[0] || '').trim();
    const back = (row[1] || '').trim();
    const tags = row.length > 2 ? [row[2].trim()] : ['brainscape'];

    if (!front && !back) continue;

    if (!front) {
      warnings.push({ line: lineNum, reason: 'Missing question', rawSnippet: back.substring(0, 40) });
      continue;
    }
    if (!back) {
      warnings.push({ line: lineNum, reason: 'Missing answer', rawSnippet: front.substring(0, 40) });
      continue;
    }

    cards.push({
      front: cleanHtml(front),
      back: cleanHtml(back),
      hint: '',
      tags: tags.filter(Boolean),
      type: CARD_TYPES.BASIC,
      clozeText: '',
      sourceLine: lineNum
    });
  }

  return buildResult('Brainscape', cards, warnings, rows.length);
}

/**
 * 5. Parse Cram.com Export (TSV or CSV with optional hint)
 */
export function parseCram(text) {
  const rows = parseDelimitedRows(text);
  const cards = [];
  const warnings = [];
  let lineNum = 0;

  for (const row of rows) {
    lineNum++;
    if (!row || row.length === 0 || (row.length === 1 && !row[0].trim())) continue;

    const front = (row[0] || '').trim();
    const back = (row[1] || '').trim();
    const hint = row.length > 2 ? (row[2] || '').trim() : '';

    if (!front && !back) continue;

    if (!front) {
      warnings.push({ line: lineNum, reason: 'Missing front side', rawSnippet: back.substring(0, 40) });
      continue;
    }
    if (!back) {
      warnings.push({ line: lineNum, reason: 'Missing back side', rawSnippet: front.substring(0, 40) });
      continue;
    }

    cards.push({
      front: cleanHtml(front),
      back: cleanHtml(back),
      hint: cleanHtml(hint),
      tags: ['cram'],
      type: CARD_TYPES.BASIC,
      clozeText: '',
      sourceLine: lineNum
    });
  }

  return buildResult('Cram.com', cards, warnings, rows.length);
}

/**
 * 6. Parse Knowt Export (Quizlet text, CSV, or Knowt JSON)
 */
export function parseKnowt(text) {
  const trimmed = text.trim();
  // Check if JSON
  if (trimmed.startsWith('{') || trimmed.startsWith('[')) {
    try {
      const data = JSON.parse(trimmed);
      const items = Array.isArray(data) ? data : (data.cards || data.terms || data.flashcards || []);
      const cards = [];
      const warnings = [];
      let idx = 0;

      for (const item of items) {
        idx++;
        const front = (item.term || item.front || item.question || '').trim();
        const back = (item.definition || item.back || item.answer || '').trim();

        if (!front && !back) continue;
        if (!front) {
          warnings.push({ line: idx, reason: 'Missing term/front', rawSnippet: back.substring(0, 40) });
          continue;
        }
        if (!back) {
          warnings.push({ line: idx, reason: 'Missing definition/back', rawSnippet: front.substring(0, 40) });
          continue;
        }

        cards.push({
          front: cleanHtml(front),
          back: cleanHtml(back),
          hint: (item.hint || '').trim(),
          tags: ['knowt'],
          type: CARD_TYPES.BASIC,
          clozeText: '',
          sourceLine: idx
        });
      }
      return buildResult('Knowt', cards, warnings, items.length);
    } catch (e) {
      // Fall through to delimited parsing
    }
  }

  // Otherwise Quizlet-style text or CSV
  return parseQuizlet(text, options);
}

/**
 * 7. Universal Delimited Parser (CSV, TSV, Semicolon, Custom)
 */
export function parseDelimited(text, options = null) {
  const customFieldSep = typeof options === 'string' ? options : (options?.fieldSeparator && options.fieldSeparator !== 'auto' ? options.fieldSeparator : null);
  const cardSep = options && typeof options === 'object' && options.cardSeparator && options.cardSeparator !== 'auto' ? options.cardSeparator : null;

  const detected = detectQuizletSeparators(text, cardSep, customFieldSep);
  if (detected.cardSeparator === ';') {
    return parseQuizlet(text, { cardSeparator: ';', fieldSeparator: detected.fieldSeparator });
  }

  const rows = parseDelimitedRows(text, detected.fieldSeparator);
  const cards = [];
  const warnings = [];
  let lineNum = 0;

  // Header detection (check for "Front", "Question", "Term")
  let startIdx = 0;
  if (rows.length > 0) {
    const r0 = rows[0].map(c => c.toLowerCase().trim());
    if (
      (r0.includes('front') || r0.includes('question') || r0.includes('term')) &&
      (r0.includes('back') || r0.includes('answer') || r0.includes('definition'))
    ) {
      startIdx = 1;
    }
  }

  for (let i = startIdx; i < rows.length; i++) {
    lineNum = i + 1;
    const row = rows[i];
    if (!row || row.length === 0 || (row.length === 1 && !row[0].trim())) continue;

    const front = (row[0] || '').trim();
    const back = (row.slice(1).join(' ') || '').trim();

    if (!front && !back) continue;

    if (!front) {
      warnings.push({ line: lineNum, reason: 'Column 1 is empty', rawSnippet: back.substring(0, 40) });
      continue;
    }
    if (!back) {
      warnings.push({ line: lineNum, reason: 'Column 2 (Answer) is empty', rawSnippet: front.substring(0, 40) });
      continue;
    }

    // Check for cloze in front
    const cloze = detectCloze(front);

    cards.push({
      front: cleanHtml(front),
      back: cleanHtml(back),
      hint: '',
      tags: ['imported'],
      type: cloze ? CARD_TYPES.CLOZE : CARD_TYPES.BASIC,
      clozeText: cloze || '',
      sourceLine: lineNum
    });
  }

  const res = buildResult('Delimited File', cards, warnings, rows.length);
  res.detectedSeparators = detected;
  return res;
}

/**
 * 8. StudyCards Native JSON Backup
 */
export function parseStudyCardsJson(jsonString) {
  try {
    const data = JSON.parse(jsonString);
    if (!data || !Array.isArray(data.cards) || !Array.isArray(data.groups)) {
      return {
        success: false,
        serviceName: 'StudyCards Backup',
        error: 'Not a valid StudyCards backup file (missing cards or groups array).',
        cards: [],
        warnings: [{ line: 1, reason: 'Invalid JSON schema', rawSnippet: '' }],
        stats: { totalRows: 0, validCards: 0, skippedRows: 0, cardTypes: {} },
        isNativeBackup: true,
        nativeData: null
      };
    }

    const typeCounts = {};
    for (const c of data.cards) {
      typeCounts[c.type || 'basic'] = (typeCounts[c.type || 'basic'] || 0) + 1;
    }

    return {
      success: true,
      serviceName: 'StudyCards Backup',
      deckName: 'StudyCards Collection',
      cards: data.cards,
      groups: data.groups,
      settings: data.settings,
      warnings: [],
      stats: {
        totalRows: data.cards.length,
        validCards: data.cards.length,
        skippedRows: 0,
        cardTypes: typeCounts,
        groupsCount: data.groups.length
      },
      isNativeBackup: true,
      nativeData: data
    };
  } catch (err) {
    return {
      success: false,
      serviceName: 'StudyCards Backup',
      error: `JSON parse error: ${err.message}`,
      cards: [],
      warnings: [{ line: 1, reason: err.message, rawSnippet: '' }],
      stats: { totalRows: 0, validCards: 0, skippedRows: 1, cardTypes: {} },
      isNativeBackup: true,
      nativeData: null
    };
  }
}

/**
 * Construct standardized parse result object
 */
function buildResult(serviceName, cards, warnings, totalRows) {
  const typeCounts = { basic: 0, cloze: 0, reversible: 0 };
  for (const c of cards) {
    if (c.type === CARD_TYPES.CLOZE) typeCounts.cloze++;
    else if (c.type === CARD_TYPES.REVERSIBLE) typeCounts.reversible++;
    else typeCounts.basic++;
  }

  return {
    success: cards.length > 0,
    serviceName,
    deckName: `${serviceName} Deck`,
    cards,
    warnings,
    stats: {
      totalRows,
      validCards: cards.length,
      skippedRows: warnings.length,
      cardTypes: typeCounts
    },
    isNativeBackup: false,
    nativeData: null
  };
}
